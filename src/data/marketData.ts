export function generateInstrumentSeries(
  instrument: MarketInstrument,
  timeframe: Timeframe
): TimeframeSeries {
  const major = MAJOR_INDICES.find((m) => m.symbol === instrument.symbol);
  if (major) {
    return major.seriesByTimeframe[timeframe];
  }

  const labelsByTf: Record<Timeframe, string[]> = {
    '1D': LABELS_1D,
    '1M': LABELS_1M,
    '3M': LABELS_3M,
    '1Y': LABELS_1Y,
    '5Y': LABELS_5Y,
    All: LABELS_ALL,
  };

  const scaleByTf: Record<Timeframe, number> = {
    '1D': Math.abs(instrument.numericChangePct) / 100 || 0.012,
    '1M': 0.048,
    '3M': 0.095,
    '1Y': 0.24,
    '5Y': 0.48,
    All: 1.15,
  };

  const endPrice = instrument.numericPrice;
  const isGain = timeframe === '1D' ? instrument.gain : instrument.numericChangePct > -2;
  const pctMove = scaleByTf[timeframe] * (isGain ? 1 : -1);
  const startPrice = endPrice / (1 + pctMove);

  // Deterministic pseudo-random wave per symbol + timeframe
  let seed = 0;
  for (let i = 0; i < instrument.symbol.length; i++) {
    seed += instrument.symbol.charCodeAt(i) * (i + 1);
  }
  seed += timeframe.charCodeAt(0) * 13;

  const labels = labelsByTf[timeframe];
  const points: ChartPoint[] = labels.map((label, i) => {
    const t = i / (labels.length - 1);
    const wave = Math.sin(t * Math.PI * 3.5 + seed) * 0.14 + Math.cos(t * Math.PI * 6 + seed * 0.5) * 0.07;
    const interpolated = startPrice + (endPrice - startPrice) * Math.max(0, Math.min(1.05, t + (1 - t) * t * wave));
    const value = i === labels.length - 1 ? endPrice : Number(interpolated.toFixed(endPrice < 10 ? 4 : 2));
    return { label, value };
  });

  const deltaVal = endPrice - startPrice;
  const deltaPct = (deltaVal / startPrice) * 100;
  const sign = deltaVal >= 0 ? '+' : '−';
  const absDelta = Math.abs(deltaVal).toFixed(endPrice < 10 ? 4 : 2);
  const absPct = Math.abs(deltaPct).toFixed(2);

  return {
    deltaText: `${sign}${absDelta} (${sign}${absPct}%)`,
    gain: deltaVal >= 0,
    points,
  };
}
