function buildSeries(
  baseValues: number[],
  labels: string[],
  deltaText: string,
  gain: boolean
): TimeframeSeries {
  return {
    deltaText,
    gain,
    points: baseValues.map((value, idx) => ({
      label: labels[idx] ?? `T${idx + 1}`,
      value,
    })),
  };
}

